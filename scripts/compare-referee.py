"""Decides, per word/form, whether the plain or the vowel-marked recording is closer to the
reference recorded from the transliteration (IPA). Writes data/src/nikkud/audio-choice.txt.
Usage: python3 scripts/compare-referee.py <PCM_DIR>"""
import json, sys, os
import numpy as np

MARGIN = 1.0  # how much closer one version must be to win
d = sys.argv[1]
pairs = json.load(open(os.path.join(d, 'pairs-ipa.json'), encoding='utf-8'))

def spec(path):
    s = np.frombuffer(open(path, 'rb').read(), dtype=np.int16).astype(float)
    env = np.array([np.abs(s[i:i + 320]).max() for i in range(0, len(s), 320)])
    v = np.where(env > 1500)[0]
    if len(v) == 0:
        return np.zeros((1, 200))
    s = s[v[0] * 320:(v[-1] + 1) * 320]
    if len(s) < 600:
        s = np.pad(s, (0, 600 - len(s)))
    return np.array([np.log1p(np.abs(np.fft.rfft(s[i:i + 512] * np.hanning(512))))[:200] for i in range(0, len(s) - 512, 160)])

def dist(a, b):
    A, B = spec(a), spec(b)
    n, m = len(A), len(B)
    C = np.linalg.norm(A[:, None, :] - B[None, :, :], axis=2)
    D = np.full((n + 1, m + 1), np.inf); D[0, 0] = 0
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            D[i, j] = C[i - 1, j - 1] + min(D[i - 1, j], D[i, j - 1], D[i - 1, j - 1])
    return D[n, m] / (n + m)

out = ['# Which recording to use where plain and vowel-marked audio differ (generated by scripts/compare-referee.py).',
       '# Decided by which version sounds closer to a reference recorded from the transliteration.',
       '# Format: id|plain text|marks or plain   (edit by hand to override)']
tally = {'marks': 0, 'plain': 0, 'tie': 0}
for p in pairs:
    dp, dn = dist(p['plainFile'], p['ipaFile']), dist(p['vocFile'], p['ipaFile'])
    choice = 'marks' if dn < dp - MARGIN else 'plain' if dp < dn - MARGIN else 'tie'
    tally[choice] += 1
    if choice != 'tie':
        out.append(f"{p['id']}|{p['plain']}|{choice}   # {p['tr']}: plain {dp:.1f}, marks {dn:.1f}")
open(os.path.join(os.path.dirname(__file__), '..', 'data', 'src', 'nikkud', 'audio-choice.txt'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(tally)
